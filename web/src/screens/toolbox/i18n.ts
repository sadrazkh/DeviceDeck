export const toolboxMessages = { en, fa: fa as Record<ToolboxKey, string> };

export type ToolboxI18n = I18n & { tt(key: ToolboxKey, vars?: Vars): string };

/** The app's I18n plus `tt` for the toolbox's own words. */
export function useToolboxI18n(): ToolboxI18n {
  const i18n = useI18n();
  return useMemo(() => {
    const table = i18n.lang === 'fa' ? toolboxMessages.fa : toolboxMessages.en;
    return { ...i18n, tt: (key: ToolboxKey, vars?: Vars) => formatMessage(i18n.lang, table[key] ?? en[key], vars) };
  }, [i18n]);
}
