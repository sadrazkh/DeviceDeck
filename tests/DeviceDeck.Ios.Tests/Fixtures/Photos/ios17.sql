-- A small Photos.sqlite in the iOS 14+ layout (as on iOS 17): assets in ZASSET, screenshots flagged by
-- ZISDETECTEDSCREENSHOT, album membership in Z_30ASSETS(Z_30ALBUMS, Z_3ASSETS). Z_40ASSETS is a join that
-- is not about albums and must be ignored. Dates: 770464800 = 2025-06-01 10:00:00Z.
CREATE TABLE Z_PRIMARYKEY (Z_ENT INTEGER PRIMARY KEY, Z_NAME VARCHAR, Z_SUPER INTEGER, Z_MAX INTEGER);
INSERT INTO Z_PRIMARYKEY VALUES (3, 'Asset', 0, 7), (29, 'GenericAlbum', 0, 4), (30, 'Album', 29, 4), (40, 'Memory', 0, 1);

CREATE TABLE ZASSET (
  Z_PK INTEGER PRIMARY KEY, Z_ENT INTEGER, Z_OPT INTEGER,
  ZCLOUDLOCALSTATE INTEGER, ZFAVORITE INTEGER, ZHIDDEN INTEGER, ZKIND INTEGER, ZKINDSUBTYPE INTEGER,
  ZSAVEDASSETTYPE INTEGER, ZTRASHEDSTATE INTEGER, ZISDETECTEDSCREENSHOT INTEGER, ZWIDTH INTEGER, ZHEIGHT INTEGER,
  ZDATECREATED TIMESTAMP, ZMODIFICATIONDATE TIMESTAMP, ZDURATION FLOAT,
  ZDIRECTORY VARCHAR, ZFILENAME VARCHAR, ZUUID VARCHAR);

CREATE TABLE ZADDITIONALASSETATTRIBUTES (
  Z_PK INTEGER PRIMARY KEY, Z_ENT INTEGER, Z_OPT INTEGER,
  ZASSET INTEGER, ZORIGINALFILESIZE INTEGER, ZORIGINALHEIGHT INTEGER, ZORIGINALWIDTH INTEGER, ZORIGINALFILENAME VARCHAR);

CREATE TABLE ZGENERICALBUM (
  Z_PK INTEGER PRIMARY KEY, Z_ENT INTEGER, Z_OPT INTEGER,
  ZKIND INTEGER, ZTRASHEDSTATE INTEGER, ZCACHEDCOUNT INTEGER, ZTITLE VARCHAR, ZUUID VARCHAR);

CREATE TABLE Z_30ASSETS (Z_30ALBUMS INTEGER, Z_3ASSETS INTEGER, Z_FOK_3ASSETS INTEGER, PRIMARY KEY (Z_30ALBUMS, Z_3ASSETS));
CREATE TABLE Z_40ASSETS (Z_40MEMORIES INTEGER, Z_3ASSETS INTEGER, PRIMARY KEY (Z_40MEMORIES, Z_3ASSETS));

